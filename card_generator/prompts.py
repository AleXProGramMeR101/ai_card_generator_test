def build_user_prompt(
    product: ProductInput,
    schema: CategorySchema | None,
    present_fields: list[str],
    absent_fields: list[str],
) -> str:
    """Собирает сообщение с данными товара и списком ожидаемых характеристик.

    Args:
        product: Товар.
        schema: Схема категории или None, если категория неизвестна.
        present_fields: Ожидаемые характеристики, которые уже есть в specs.
        absent_fields: Ожидаемые характеристики, которых нет в specs.

    Returns:
        Текст сообщения для модели.
    """
    product_data = {
        "Название": product.name,
        "Категория": product.category,
        "Производитель": product.manufacturer,
        "Характеристики": product.filled_specs(),
        "Описание": product.description,
    }
    product_data = {key: value for key, value in product_data.items() if value}
    product_json = json.dumps(product_data, ensure_ascii=False, indent=2)
    if schema is None:
        schema_block = (
            "Списка ожидаемых характеристик для этого типа товара нет - заполни suggested_fields "
            "характеристиками, которых нет в блоке «Характеристики», и поищи их значения в описании."
        )
    else:
        present = ", ".join(present_fields) or "нет"
        absent = ", ".join(absent_fields) or "нет"
        schema_block = (
            f"Категория: {schema.name}. suggested_fields оставь пустым.\n"
            f"Ожидаемые характеристики, которые уже есть в блоке «Характеристики»: {present}.\n"
            f"Ожидаемые характеристики, которых нет в блоке «Характеристики» (поищи их значения в описании): {absent}."
        )
    return f"Данные о товаре:\n{product_json}\n\n{schema_block}"


def build_repair_prompt(problems: list[str]) -> str:
    """Собирает сообщение с ошибками предыдущего ответа.

    Args:
        problems: Найденные проблемы.

    Returns:
        Текст сообщения для модели.
    """
    listed = "\n".join(f"- {problem}" for problem in problems)
    return (
        f"В ответе есть ошибки:\n{listed}\n\n"
        "Исправь их и верни JSON целиком в той же структуре. Остальное без необходимости не меняй. "
        "Не добавляй числа, которых нет во входных данных."
    )
